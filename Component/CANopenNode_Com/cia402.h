/**
 * Commands from CIA402 0x6060 Modes Of Operation
 * Commands from CIA402 0x6061 Modes of operation display
 */
typedef enum {
	OPERATING_NONE = 0x00,
    PROFILE_POSITION_MODE = 0x01,
    PROFILE_VELOCITY_MODE = 0x03,
    PROFILE_TORQUE_MODE = 0x04,
    HOMING_MODE = 0x06,  // Not supported
    INTERPOLATED_POSITION_MODE = 0x07, // Not supported
    CYCLIC_SYNCHRONOUS_POSITION_MODE = 0x08,
    CYCLIC_SYNCHRONOUS_VELOCITY_MODE = 0x09,
    CYCLIC_SYNCHRONOUS_TORQUE_MODE = 0x0A
} CO_OperatingMode_t;

